#include "shellScript.h"


void ShellScript::createShellScript(const std::string& fileName, int numberOfUav, const std::vector<initialStates>& initialStates) {
    // Open a file in write mode
    std::ofstream file(fileName);

    // Check if the file was successfully opened
    if (!file.is_open()) {
        std::cerr << "Error: Unable to create file " << fileName << "\n";
        return;
    }

    // Write to the file
    m_writeHeader(file);
    m_writeCheckBinaryPath(file, "~/Documents/Ardupilot_GRS/build/sitl/bin/arduplane");
    m_writeVehicleCreation(file, numberOfUav, initialStates);

    // Close the file
    file.close();

    // Make the script executable
    const std::string chmodCommand = "chmod +x " + fileName;
    if (system(chmodCommand.c_str()) != 0) {
        std::cerr << "Error: Failed to make the script executable\n";
    } else {
        std::cout << "Shell script '" << fileName << "' created and made executable.\n";
    }
}

void ShellScript::m_writeHeader(std::ofstream& file) {

    // Get the current date
    const std::time_t now = std::time(nullptr);
    const std::tm* localTime = std::localtime(&now);

    char dateBuffer[11]; // Enough space for "YYYY-MM-DD" and null terminator
    std::strftime(dateBuffer, sizeof(dateBuffer), "%Y-%m-%d", localTime);

    file << "#!/bin/bash\n\n";
    file << "# This script was generated by GRS simulation environment\n";
    file << "# Generated on : " << dateBuffer << "\n\n";
}

void ShellScript::m_writeCheckBinaryPath(std::ofstream& file, const std::string& binaryPath) {

    file << "# Set pixHawk binary path\n";
    file << "ARDUPLANE=" << binaryPath << "\n\n";

    file << "if [ -f \"$ARDUPLANE\" ];\n";
    file << "then\n";
    file << "    echo \"Found SITL executable\"\n";
    file << "else\n";
    file << "    echo \"SITL executable not found ($ARDUPLANE). Exiting\"\n";
    file << "exit\n";
    file << "fi\n\n";

    file << "[ -x \"$ARDUPLANE\" ] || {\n";
	file << "    echo \"SITL binary not executable ($ARDUPLANE). Exiting\"\n";
	file << "    exit\n";
    file << "}\n";
}

